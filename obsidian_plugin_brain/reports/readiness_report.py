from __future__ import annotations

import json
from typing import Any


def render_readiness_report(imported: dict[str, Any], synthesis: dict[str, Any]) -> str:
    """Render a source-cited Markdown readiness and scope audit report."""
    manifest = imported.get("manifest") or {}
    plugin_id = manifest.get("id", "unknown-plugin")
    plugin_name = manifest.get("name", plugin_id)
    version = manifest.get("version", "0.0.0")
    min_app = manifest.get("minAppVersion", "0.0.0")
    desktop_only = bool(manifest.get("isDesktopOnly", False))
    bundler = imported.get("bundler") or "undetected"
    scopes = synthesis.get("scopes") or []
    score = synthesis.get("static_signal_score", 0)
    gate = synthesis.get("gate_status", "blocked-critical")
    counts = synthesis.get("counts") or {}
    findings = synthesis.get("findings") or []

    lines: list[str] = [
        "---",
        'type: "report"',
        "title: " + json.dumps(f"Obsidian Plugin Static Review: {plugin_name}"),
        'status: "active"',
        'confidence: "practitioner"',
        "---",
        "",
        f"# Obsidian Plugin Static Review: {plugin_name} (`{plugin_id}`)",
        "",
        "Advisory static analysis generated by `obsidian-plugin-brain` (read-only; zero plugin code executed).",
        "Delivery: editable source checkout with adjacent scripts and reference files; standalone wheel installation is unsupported.",
        "",
        "## Executive Summary",
        "",
        f"- **Static Signal Score:** `{score}/100` (selected heuristics only)",
        f"- **Static Review Verdict:** `{gate}`",
        "- **Release readiness:** unverified. No lint, compilation, Obsidian runtime, mobile device, or directory acceptance was tested.",
        f"- **Plugin Version / Min Obsidian Version:** `{version}` / `{min_app}`",
        f"- **Platform Target:** `{'Desktop only (Electron)' if desktop_only else 'Cross-platform (Desktop + iOS + Android)'}`",
        f"- **Detected Bundler:** `{bundler}`",
        f"- **Finding Tallies:** `{counts.get('critical', 0)}` critical, `{counts.get('warning', 0)}` warnings, `{counts.get('info', 0)}` advisory, `{counts.get('pass', 0)}` passed",
        "",
        "## Detected Plugin Scopes",
        "",
    ]

    for scope in scopes:
        lines.append(f"- `{scope}`")

    lines.extend(
        [
            "",
            "## Rule-by-Rule Findings and Citations",
            "",
            "| Rule | Severity | Status | Scope | Finding and Source Citations |",
            "|---|---|---|---|---|",
        ]
    )

    for item in findings:
        sources = ", ".join(f"[{sid}]({url})" for sid, url in zip(item.get("source_ids", []), item.get("source_urls", [])))
        canon = item.get("canon_note", "")
        canon_link = f"[[{canon}]]" if canon else ""
        detail = f"{item['message']} ({item['confidence']}; {canon_link}; sources: {sources})".replace("|", "\\|").replace("\n", " ")
        lines.append(
            f"| `{item['rule_id']}` | `{item['severity']}` | `{item['status']}` | `{item['scope']}` | {detail} |"
        )

    actionable = [f for f in findings if f.get("status") != "pass"]
    lines.extend(["", "## Required Remediations and Rollback Discipline", ""])
    if not actionable:
        lines.append(
            "- All evaluated static rules passed. Proceed to live Obsidian profiling and manual review checklist in [[Community Store submission, eslint-plugin review gates, BRAT, and release CI]]."
        )
    else:
        for item in actionable:
            lines.append(
                f"- **`{item['rule_id']}` ({item['severity']}):** {item['remediation']} Rollback: revert plugin source/config changes in Git prior to tagging release."
            )

    warnings = imported.get("warnings") or []
    no_data = imported.get("no_data") or []
    lines.extend(["", "## Unverified Runtime Surfaces (No Data)", ""])
    for nd in no_data:
        lines.append(f"- **NO DATA (requires live Obsidian check):** {nd}")
    for warn in warnings:
        lines.append(f"- **Importer note:** {warn}")

    lines.extend(
        [
            "",
            "## Related Operating Notes",
            "",
            "- [[Plugin lifecycle, Component ownership, and cleanup discipline]]",
            "- [[Workspace leaves, custom ItemView dashboards, and deferred views]]",
            "- [[3D WebGL, Three.js, React Three Fiber, and spatial codex views]]",
            "- [[CodeMirror 6 architecture, StateFields, ViewPlugins, and Live Preview]]",
            "- [[Mobile compatibility, startup performance, and memory profiling]]",
            "- [[Security, XSS prevention, Sync storage limits, and network disclosure]]",
            "- [[Community Store submission, eslint-plugin review gates, BRAT, and release CI]]",
            "",
        ]
    )
    return "\n".join(lines)
